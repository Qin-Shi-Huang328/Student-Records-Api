create table if not exists students (
  student_id        text primary key,
  full_name         text not null,
  contact_number    text,
  email             text,
  address           text,
  year_level        smallint check (year_level between 1 and 6),
  section           text,
  enrollment_status text not null default 'not-enrolled'
                    check (enrollment_status in ('enrolled','not-enrolled','irregular')),
  password_hash     text,
  created_at        timestamptz not null default now(),
  updated_at        timestamptz not null default now()
);

create table if not exists employees (
  employee_id   text primary key,
  full_name     text not null,
  role          text not null default 'staff',
  password_hash text
);

create table if not exists grades (
  grade_id     bigint generated by default as identity primary key,
  student_id   text not null references students(student_id) on delete cascade,
  subject_code text not null,
  subject_name text not null,
  school_year  text,
  semester     text,
  grade        numeric(5,2) check (grade is null or (grade between 0 and 100)),
  remarks      text
);

create table if not exists document_requests (
  request_id    bigint generated by default as identity primary key,
  student_id    text not null references students(student_id) on delete cascade,
  document_type text not null,
  status        text not null default 'pending',
  requested_at  timestamptz not null default now(),
  released_at   timestamptz
);

-- audit_log has NO foreign key on purpose: deleting a student must not erase its history.
create table if not exists audit_log (
  log_id        bigint generated by default as identity primary key,
  student_id    text not null,
  field_changed text not null,
  old_value     text,
  new_value     text,
  changed_by    text not null default 'Unknown',
  changed_at    timestamptz not null default now()
);

create index if not exists students_full_name_idx on students(full_name);
create index if not exists grades_student_id_idx on grades(student_id);
create index if not exists document_requests_student_id_idx on document_requests(student_id);
create index if not exists audit_log_student_changed_at_idx on audit_log(student_id, changed_at desc);

-- Fixes for databases created by the earlier schema (no-ops on a fresh database)
alter table audit_log drop constraint if exists audit_log_student_id_fkey;
alter table students alter column enrollment_status set default 'not-enrolled';

-- Lock tables from the public Supabase API. The backend connects directly with DATABASE_URL.
alter table students enable row level security;
alter table employees enable row level security;
alter table grades enable row level security;
alter table document_requests enable row level security;
alter table audit_log enable row level security;
